/**
 * topics/curl.js - The Curl (∇×A) Visualizer
 * Visualizes curl as local rotation, swirl, and vorticity of a vector field.
 * Designed to match Image 2: 3Blue1Brown aesthetic with dark background,
 * 4 controllable vortex centers on the 2D Cartesian plane,
 * fiery orange/yellow/red streamlines, circulating white arrow loops,
 * and text labels (curl F > 0 vs curl F < 0).
 */

import * as THREE from 'three';

let curlGroup = null;
let vectorsGroup = null;
let ringsGroup = null;
let particlesMesh = null;
let particlePositions = null;
let particleData = [];

// 4 Controllable Vortices on the 2D plane matching Image 2
// Default configuration:
// - Left: x=-2.2, y=0.0, gamma=+2.0 (curl F > 0, CCW)
// - Right: x=+2.2, y=0.0, gamma=+2.0 (curl F > 0, CCW)
// - Top: x=0.0, y=+1.4, gamma=-2.0 (curl F < 0, CW)
// - Bottom: x=0.0, y=-1.4, gamma=-2.0 (curl F < 0, CW)
export const DEFAULT_CURL_VORTICES = [
  { id: 1, x: -2.2, y: 0.0, gamma: 2.2 },  // Left: CCW, curl > 0
  { id: 2, x: 2.2, y: 0.0, gamma: 2.2 },   // Right: CCW, curl > 0
  { id: 3, x: 0.0, y: 1.4, gamma: -2.2 },  // Top: CW, curl < 0
  { id: 4, x: 0.0, y: -1.4, gamma: -2.2 }  // Bottom: CW, curl < 0
];

let vortices = JSON.parse(JSON.stringify(DEFAULT_CURL_VORTICES));
let activeVortexIndex = 0; // 0 to 3
const NUM_PARTICLES = 480;
const EPS_SMOOTH = 0.38;

/**
 * Computes 2D swirling vector field at (x, y) generated by the 4 vortices
 * F(x, y) = sum_i gamma_i * (-dy * i + dx * j) / (|r - r_i|^2 + eps^2)
 */
export function evalCurlField(x, y) {
  let Fx = 0;
  let Fy = 0;

  // If all vortices are zero, simulate uniform irrotational laminar flow:
  const allZero = vortices.every(v => Math.abs(v.gamma) < 0.05);
  if (allZero) {
    return { Fx: 1.2, Fy: 0, mag: 1.2 };
  }

  for (let i = 0; i < vortices.length; i++) {
    const v = vortices[i];
    if (Math.abs(v.gamma) < 0.05) continue;
    const dx = x - v.x;
    const dy = y - v.y;
    const r2 = dx * dx + dy * dy;
    const denom = r2 + EPS_SMOOTH * EPS_SMOOTH;
    const factor = v.gamma / denom;
    // Tangential circulation: (-dy, dx)
    Fx += factor * (-dy);
    Fy += factor * dx;
  }

  const mag = Math.sqrt(Fx * Fx + Fy * Fy);
  return { Fx, Fy, mag };
}

/**
 * Creates bold number sprite (1, 2, 3, 4) centered inside vortex disk
 * Matches divergence point color scheme:
 * - Red CCW: Crisp white with dark outline for contrast
 * - Blue CW: Deep dark navy #090e1a (identical to divergence sink on blue disk)
 * - Slate Zero: Crisp white with dark outline #090e1a (identical to divergence zero)
 */
function createVortexNumberSprite(numberStr, isCCW, isZero) {
  const canvas = document.createElement('canvas');
  canvas.width = 128;
  canvas.height = 128;
  const ctx = canvas.getContext('2d');

  ctx.clearRect(0, 0, 128, 128);
  ctx.font = '900 84px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';

  if (isZero) {
    ctx.lineWidth = 6;
    ctx.strokeStyle = '#090e1a';
    ctx.strokeText(numberStr, 64, 68);
    ctx.fillStyle = '#ffffff';
    ctx.fillText(numberStr, 64, 68);
  } else if (!isCCW) {
    // Blue CW: dark navy text on light blue disk
    ctx.fillStyle = '#090e1a';
    ctx.fillText(numberStr, 64, 68);
  } else {
    // Red CCW: crisp white text with dark outline on red disk
    ctx.lineWidth = 6;
    ctx.strokeStyle = '#090e1a';
    ctx.strokeText(numberStr, 64, 68);
    ctx.fillStyle = '#ffffff';
    ctx.fillText(numberStr, 64, 68);
  }

  const texture = new THREE.CanvasTexture(canvas);
  texture.minFilter = THREE.LinearFilter;
  const spriteMat = new THREE.SpriteMaterial({
    map: texture,
    transparent: true,
    depthTest: false,
    renderOrder: 99
  });
  const sprite = new THREE.Sprite(spriteMat);
  sprite.scale.set(0.22, 0.22, 1);
  return sprite;
}

/**
 * Uniform Topic Module Contract: init()
 */
export function init(group, coordSystem, params) {
  curlGroup = new THREE.Group();
  group.add(curlGroup);

  if (params.curlVortices) {
    vortices = JSON.parse(JSON.stringify(params.curlVortices));
  } else {
    vortices = JSON.parse(JSON.stringify(DEFAULT_CURL_VORTICES));
  }
  activeVortexIndex = params.activeVortexIndex !== undefined ? params.activeVortexIndex % 4 : 0;

  buildScene(params);
}

/**
 * Builds the dense 3Blue1Brown vector field, circulation loops, and fluid streamlines
 */
function buildScene(params) {
  while (curlGroup.children.length > 0) {
    const child = curlGroup.children.pop();
    if (child.geometry) child.geometry.dispose();
    if (child.material) {
      if (Array.isArray(child.material)) child.material.forEach(m => m.dispose());
      else child.material.dispose();
    }
  }

  vectorsGroup = new THREE.Group();
  ringsGroup = new THREE.Group();
  curlGroup.add(vectorsGroup);
  curlGroup.add(ringsGroup);

  // 1. Dense 2D Vector Field with 3Blue1Brown Color Scheme (Red -> Orange -> Gold -> Cyan)
  const stepX = 0.26;
  const stepY = 0.26;
  const col = new THREE.Color();

  for (let x = -3.8; x <= 3.8; x += stepX) {
    for (let y = -2.6; y <= 2.6; y += stepY) {
      const { Fx, Fy, mag } = evalCurlField(x, y);
      if (mag > 0.05) {
        const dir = new THREE.Vector3(Fx / mag, Fy / mag, 0);
        const len = Math.min(0.24, Math.max(0.08, mag * 0.12));

        // 3Blue1Brown Heat Colormap matching Image 2:
        // High speed (between vortices): Vibrant Yellow/Gold
        // Medium speed: Warm Orange
        // Outer boundaries: Deep Crimson / Red
        const t = Math.min(1.0, mag / 2.6);
        if (t > 0.6) {
          // Yellow-Gold
          col.setHSL(0.14, 1.0, 0.55);
        } else if (t > 0.3) {
          // Orange
          col.setHSL(0.07, 1.0, 0.5);
        } else {
          // Crimson / Dark Red
          col.setHSL(0.0, 0.9, 0.4);
        }

        const arr = new THREE.ArrowHelper(
          dir,
          new THREE.Vector3(x, y, 0),
          len,
          col.getHex(),
          len * 0.4,
          len * 0.2
        );
        arr.line.material.transparent = true;
        arr.line.material.opacity = 0.65 + 0.3 * t;
        vectorsGroup.add(arr);
      }
    }
  }

  // 2. Circular Circulation Loops with Circulating White Arrows matching Divergence Scheme
  vortices.forEach((v, idx) => {
    const isZero = Math.abs(v.gamma) < 0.05;
    const isCCW = !isZero && v.gamma > 0;
    const ringRadius = 0.52;
    const arrowCount = 4;

    // Center Core Indicator (matches divergence geometry with red kept for CCW)
    const coreGeo = new THREE.CircleGeometry(0.14, 24);
    let coreColor = 0xef4444; // CCW: Red (kept instead of orange as requested)
    if (isZero) coreColor = 0x64748b; // Zero: Slate (matches divergence)
    else if (!isCCW) coreColor = 0x38bdf8; // CW: Light Blue (matches divergence sink)

    const coreMat = new THREE.MeshBasicMaterial({
      color: coreColor,
      transparent: true,
      opacity: 0.95
    });
    const coreMesh = new THREE.Mesh(coreGeo, coreMat);
    coreMesh.position.set(v.x, v.y, 0.02);
    ringsGroup.add(coreMesh);

    // Glowing Core Aura Ring (matches divergence geometry)
    const auraGeo = new THREE.RingGeometry(0.14, 0.26, 32);
    let auraColor = 0xb91c1c; // CCW: Red aura
    if (isZero) auraColor = 0x334155; // Zero: Slate aura
    else if (!isCCW) auraColor = 0x0284c7; // CW: Light Blue aura

    const auraMat = new THREE.MeshBasicMaterial({
      color: auraColor,
      transparent: true,
      opacity: isZero ? 0.3 : 0.45,
      side: THREE.DoubleSide
    });
    const auraMesh = new THREE.Mesh(auraGeo, auraMat);
    auraMesh.position.set(v.x, v.y, 0.015);
    ringsGroup.add(auraMesh);

    // Number sprite inside the center of the vortex (high contrast matching divergence)
    const numSprite = createVortexNumberSprite(String(idx + 1), isCCW, isZero);
    numSprite.position.set(v.x, v.y, 0.05);
    ringsGroup.add(numSprite);

    // Ring boundary wire
    const ringCurve = new THREE.EllipseCurve(v.x, v.y, ringRadius, ringRadius, 0, 2 * Math.PI, false, 0);
    const ringPts = ringCurve.getPoints(48);
    const ringGeo = new THREE.BufferGeometry().setFromPoints(ringPts);
    const ringLine = new THREE.LineLoop(ringGeo, new THREE.LineBasicMaterial({
      color: isZero ? 0x94a3b8 : 0xffffff,
      transparent: true,
      opacity: isZero ? 0.25 : 0.4
    }));
    ringsGroup.add(ringLine);

    // If strength is zero, skip perimeter arrows
    if (isZero) return;

    // 4 Circulating White Arrows along the Loop Perimeter
    for (let a = 0; a < arrowCount; a++) {
      const angle = (a / arrowCount) * 2 * Math.PI;
      const rx = v.x + ringRadius * Math.cos(angle);
      const ry = v.y + ringRadius * Math.sin(angle);

      // Tangent vector: CCW is (-sin, cos), CW is (sin, -cos)
      const tangentDir = isCCW
        ? new THREE.Vector3(-Math.sin(angle), Math.cos(angle), 0).normalize()
        : new THREE.Vector3(Math.sin(angle), -Math.cos(angle), 0).normalize();

      const arr = new THREE.ArrowHelper(
        tangentDir,
        new THREE.Vector3(rx, ry, 0.03),
        0.28,
        0xffffff,
        0.11,
        0.06
      );
      arr.line.material.linewidth = 3;
      ringsGroup.add(arr);
    }
  });

  // 3. Animated Swirling Streamline Particles
  initParticles();
}

function initParticles() {
  particlePositions = new Float32Array(NUM_PARTICLES * 3);
  particleData = [];

  for (let i = 0; i < NUM_PARTICLES; i++) {
    // Spawn around one of the 4 vortices
    const v = vortices[i % vortices.length];
    const randAngle = Math.random() * 2 * Math.PI;
    const randR = 0.25 + Math.random() * 1.6;

    const x = v.x + randR * Math.cos(randAngle);
    const y = v.y + randR * Math.sin(randAngle);

    particlePositions[i * 3] = x;
    particlePositions[i * 3 + 1] = y;
    particlePositions[i * 3 + 2] = 0.04;

    particleData.push({
      x, y,
      speed: 1.1 + Math.random() * 0.7,
      life: Math.random() * 100,
      maxLife: 80 + Math.random() * 100
    });
  }

  const pGeo = new THREE.BufferGeometry();
  pGeo.setAttribute('position', new THREE.BufferAttribute(particlePositions, 3));
  const pMat = new THREE.PointsMaterial({
    color: 0xffedd5,
    size: 0.09,
    transparent: true,
    opacity: 0.85,
    blending: THREE.AdditiveBlending
  });
  particlesMesh = new THREE.Points(pGeo, pMat);
  curlGroup.add(particlesMesh);
}

/**
 * Uniform Topic Module Contract: update()
 */
export function update(time, coordSystem, params) {
  // Check if vortices data changed
  if (params.curlVortices) {
    let changed = false;
    for (let i = 0; i < 4; i++) {
      if (Math.abs(params.curlVortices[i].x - vortices[i].x) > 0.01 ||
          Math.abs(params.curlVortices[i].y - vortices[i].y) > 0.01 ||
          Math.abs(params.curlVortices[i].gamma - vortices[i].gamma) > 0.01) {
        changed = true;
        break;
      }
    }
    if (changed) {
      vortices = JSON.parse(JSON.stringify(params.curlVortices));
      buildScene(params);
    }
  }

  if (vectorsGroup) vectorsGroup.visible = params.showVectors !== false;
  if (ringsGroup) ringsGroup.visible = params.showSurfaces !== false;

  // Animate fluid streamline particles swirling through the vortices
  if (particlesMesh && particlePositions && particleData.length > 0) {
    const dt = 0.016;

    for (let i = 0; i < NUM_PARTICLES; i++) {
      const p = particleData[i];
      p.life += dt * 30;

      const { Fx, Fy, mag } = evalCurlField(p.x, p.y);

      if (p.life > p.maxLife || mag < 0.02 || Math.abs(p.x) > 4.2 || Math.abs(p.y) > 3.0) {
        // Respawn near one of the vortices
        const v = vortices[Math.floor(Math.random() * vortices.length)];
        const ang = Math.random() * 2 * Math.PI;
        const rad = 0.3 + Math.random() * 0.9;
        p.x = v.x + rad * Math.cos(ang);
        p.y = v.y + rad * Math.sin(ang);
        p.life = 0;
      } else {
        const step = p.speed * dt * 1.6;
        p.x += (Fx / (mag + 0.6)) * step;
        p.y += (Fy / (mag + 0.6)) * step;
      }

      particlePositions[i * 3] = p.x;
      particlePositions[i * 3 + 1] = p.y;
    }
    particlesMesh.geometry.attributes.position.needsUpdate = true;
  }
}

/**
 * Uniform Topic Module Contract: getFormulaData()
 * HUD contains:
 * 1. Mathematical formulation with cross product determinant matrices for the three different coordinate systems (Cartesian, Cylindrical, Spherical)
 * 2. Conservative state
 * 3. Point distribution
 */
export function getFormulaData(coordSystem, params) {
  const currentVort = params.curlVortices || vortices;
  const numCCW = currentVort.filter(v => v.gamma > 0.05).length;
  const numCW = currentVort.filter(v => v.gamma < -0.05).length;
  const numZeros = currentVort.filter(v => Math.abs(v.gamma) <= 0.05).length;
  const netGamma = currentVort.reduce((acc, v) => acc + v.gamma, 0);

  // Active mathematical formulation with cross product determinant matrices for the THREE coordinate systems
  const formulaLatex = `\\begin{aligned}
\\nabla \\times \\vec{A} &= \\begin{vmatrix} \\hat{a}_x & \\hat{a}_y & \\hat{a}_z \\\\[2pt] \\frac{\\partial}{\\partial x} & \\frac{\\partial}{\\partial y} & \\frac{\\partial}{\\partial z} \\\\[4pt] A_x & A_y & A_z \\end{vmatrix} \\\\[10pt]
\\nabla \\times \\vec{A} &= \\frac{1}{\\rho}\\begin{vmatrix} \\hat{a}_\\rho & \\rho\\hat{a}_\\phi & \\hat{a}_z \\\\[2pt] \\frac{\\partial}{\\partial \\rho} & \\frac{\\partial}{\\partial \\phi} & \\frac{\\partial}{\\partial z} \\\\[4pt] A_\\rho & \\rho A_\\phi & A_z \\end{vmatrix} \\\\[10pt]
\\nabla \\times \\vec{A} &= \\frac{1}{r^2\\sin\\theta}\\begin{vmatrix} \\hat{a}_r & r\\hat{a}_\\theta & r\\sin\\theta\\hat{a}_\\phi \\\\[2pt] \\frac{\\partial}{\\partial r} & \\frac{\\partial}{\\partial \\theta} & \\frac{\\partial}{\\partial \\phi} \\\\[4pt] A_r & r A_\\theta & r\\sin\\theta A_\\phi \\end{vmatrix}
\\end{aligned}`;

  const isConservative = Math.abs(netGamma) < 0.05;
  const conservativeValue = isConservative
    ? '∇×A = 0 (Conservative / Irrotational Flow)'
    : `∇×A ≠ 0 (Net Circulation: ${netGamma > 0 ? '+' : ''}${netGamma.toFixed(1)})`;

  const pointDistValue = `${numCCW} CCW (+Γ), ${numCW} CW (-Γ), ${numZeros} Zero (Γ=0)`;

  return {
    topicTag: 'Curl',
    topicTitle: 'The Curl (∇×A)',
    modeBtnText: 'Reset 4-Vortex Layout',
    modeDesc: 'Curl measures the microscopic circulation (vorticity) per unit area. Vector fields with ∇×A = 0 are conservative/irrotational, while ∇×A > 0 and ∇×A < 0 indicate counter-clockwise and clockwise rotation.',
    formulaLatex,
    probeSubtitle: 'Conservative State & Point Distribution',
    detailTitle: '',
    detailLatex: '', // Hides redundant detail box
    readout: [
      { label: 'Conservative State', value: conservativeValue },
      { label: 'Point Distribution', value: pointDistValue }
    ]
  };
}

