/**
 * topics/divergence.js - Divergence (∇·A) Visualizer
 * Visualizes divergence as the net outward flux from sources (faucets) and sinks (drains).
 * Designed to match Image 1: deep dark background with dense vector field,
 * 4 controllable points on the 2D Cartesian plane, animated streaming particles,
 * and circular white arrow indicator rings (outward for div > 0, inward for div < 0).
 */

import * as THREE from 'three';

let divergenceGroup = null;
let vectorsGroup = null;
let ringsGroup = null;
let particlesMesh = null;
let particlePositions = null;
let particleData = [];

// 4 Controllable Points on the 2D plane (x, y, strength q)
// Default configuration: 2 Sources (q > 0) and 2 Sinks (q < 0)
export const DEFAULT_DIVERGENCE_POINTS = [
  { id: 1, x: -1.8, y: 1.2, q: 2.0 },   // Top-left Source
  { id: 2, x: 1.8, y: 1.2, q: 2.0 },    // Top-right Source
  { id: 3, x: -1.8, y: -1.2, q: -2.0 }, // Bottom-left Sink
  { id: 4, x: 1.8, y: -1.2, q: -2.0 }   // Bottom-right Sink
];

let points = JSON.parse(JSON.stringify(DEFAULT_DIVERGENCE_POINTS));
let activePointIndex = 0; // 0 to 3
const NUM_PARTICLES = 450;
const EPS_SMOOTH = 0.35;

/**
 * Computes 2D vector field at (x, y) generated by the 4 points
 * F(x, y) = sum_i q_i * (r - r_i) / (|r - r_i|^2 + eps^2)
 */
export function evalField(x, y) {
  let Fx = 0;
  let Fy = 0;
  let totalActiveQ = 0;

  for (let i = 0; i < points.length; i++) {
    const p = points[i];
    totalActiveQ += Math.abs(p.q);
    if (Math.abs(p.q) < 0.02) continue;
    const dx = x - p.x;
    const dy = y - p.y;
    const r2 = dx * dx + dy * dy;
    const denom = r2 + EPS_SMOOTH * EPS_SMOOTH;
    const factor = p.q / denom;
    Fx += factor * dx;
    Fy += factor * dy;
  }

  // Pure solenoidal / eddyless field when all points are set to zero:
  // div(A) = d(1.2)/dx + d(0)/dy = 0!
  if (totalActiveQ < 0.05) {
    Fx = 1.2;
    Fy = 0.0;
  }

  const mag = Math.sqrt(Fx * Fx + Fy * Fy);
  return { Fx, Fy, mag, totalActiveQ };
}

/**
 * Creates high-contrast bold number sprite (1, 2, 3, 4) centered inside point disk
 */
function createPointNumberSprite(numberStr, isSource, isZero) {
  const canvas = document.createElement('canvas');
  canvas.width = 128;
  canvas.height = 128;
  const ctx = canvas.getContext('2d');

  ctx.clearRect(0, 0, 128, 128);
  ctx.font = '900 84px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';

  // High contrast text: dark for bright yellow source, bright white for sink or slate zero
  if (isSource) {
    ctx.fillStyle = '#0f172a';
  } else if (isZero) {
    ctx.fillStyle = '#f8fafc';
  } else {
    ctx.fillStyle = '#ffffff';
  }
  ctx.fillText(numberStr, 64, 68);

  const texture = new THREE.CanvasTexture(canvas);
  texture.minFilter = THREE.LinearFilter;
  const spriteMat = new THREE.SpriteMaterial({
    map: texture,
    transparent: true,
    depthTest: false,
    renderOrder: 99
  });
  const sprite = new THREE.Sprite(spriteMat);
  sprite.scale.set(0.24, 0.24, 1);
  return sprite;
}

/**
 * Uniform Topic Module Contract: init()
 */
export function init(group, coordSystem, params) {
  divergenceGroup = new THREE.Group();
  group.add(divergenceGroup);

  if (params.divPoints) {
    points = JSON.parse(JSON.stringify(params.divPoints));
  } else {
    points = JSON.parse(JSON.stringify(DEFAULT_DIVERGENCE_POINTS));
  }
  activePointIndex = params.activePointIndex !== undefined ? params.activePointIndex % 4 : 0;

  buildScene(params);
}

/**
 * Builds the dense vector field, indicator rings, and particle streamers
 */
function buildScene(params) {
  while (divergenceGroup.children.length > 0) {
    const child = divergenceGroup.children.pop();
    if (child.geometry) child.geometry.dispose();
    if (child.material) {
      if (Array.isArray(child.material)) child.material.forEach(m => m.dispose());
      else child.material.dispose();
    }
  }

  vectorsGroup = new THREE.Group();
  ringsGroup = new THREE.Group();
  divergenceGroup.add(vectorsGroup);
  divergenceGroup.add(ringsGroup);

  // 1. Dense 2D Vector Field Grid across [-3.8, 3.8] x [-2.6, 2.6] matching Image 1
  const stepX = 0.28;
  const stepY = 0.28;
  const col = new THREE.Color();

  for (let x = -3.8; x <= 3.8; x += stepX) {
    for (let y = -2.6; y <= 2.6; y += stepY) {
      const { Fx, Fy, mag, totalActiveQ } = evalField(x, y);
      if (mag > 0.05) {
        const dir = new THREE.Vector3(Fx / mag, Fy / mag, 0);
        const len = Math.min(0.24, Math.max(0.08, mag * 0.12));

        // Color coding: matching Image 1
        // Low velocity: deep slate/cyan -> Medium: bright turquoise/green -> High: golden/yellow
        const t = Math.min(1.0, mag / 3.0);
        col.setHSL(0.55 - 0.45 * t, 0.85, 0.35 + 0.35 * t);

        const arr = new THREE.ArrowHelper(
          dir,
          new THREE.Vector3(x, y, 0),
          len,
          col.getHex(),
          len * 0.4,
          len * 0.2
        );
        arr.line.material.transparent = true;
        arr.line.material.opacity = 0.55 + 0.35 * t;
        vectorsGroup.add(arr);
      }
    }
  }

  // 2. Circular Indicator Rings with White Arrows around the 4 Points (Exact match to Image 1)
  points.forEach((p, idx) => {
    const isZero = Math.abs(p.q) < 0.05;
    const isSource = !isZero && p.q > 0;
    const ringRadius = 0.55;
    const ringCount = 12;

    // Center Core Disk
    const coreGeo = new THREE.CircleGeometry(0.14, 24);
    let coreColor = 0xfacc15; // Source: yellow
    if (isZero) coreColor = 0x64748b; // Zero: slate
    else if (!isSource) coreColor = 0x38bdf8; // Sink: blue

    const coreMat = new THREE.MeshBasicMaterial({
      color: coreColor,
      transparent: true,
      opacity: 0.95
    });
    const coreMesh = new THREE.Mesh(coreGeo, coreMat);
    coreMesh.position.set(p.x, p.y, 0.02);
    ringsGroup.add(coreMesh);

    // Glowing core aura ring
    const auraGeo = new THREE.RingGeometry(0.14, 0.26, 32);
    let auraColor = 0xca8a04;
    if (isZero) auraColor = 0x334155;
    else if (!isSource) auraColor = 0x0284c7;

    const auraMat = new THREE.MeshBasicMaterial({
      color: auraColor,
      transparent: true,
      opacity: isZero ? 0.3 : 0.45,
      side: THREE.DoubleSide
    });
    const auraMesh = new THREE.Mesh(auraGeo, auraMat);
    auraMesh.position.set(p.x, p.y, 0.015);
    ringsGroup.add(auraMesh);

    // Number sprite inside the center of the point
    const numSprite = createPointNumberSprite(String(idx + 1), isSource, isZero);
    numSprite.position.set(p.x, p.y, 0.05);
    ringsGroup.add(numSprite);

    // Circular ring boundary wire
    const circleCurve = new THREE.EllipseCurve(p.x, p.y, ringRadius, ringRadius, 0, 2 * Math.PI, false, 0);
    const circlePts = circleCurve.getPoints(48);
    const circleGeo = new THREE.BufferGeometry().setFromPoints(circlePts);
    const circleLine = new THREE.LineLoop(circleGeo, new THREE.LineBasicMaterial({
      color: isZero ? 0x94a3b8 : 0xffffff,
      transparent: true,
      opacity: isZero ? 0.25 : 0.35
    }));
    ringsGroup.add(circleLine);

    // If strength is zero (q = 0), skip drawing radial arrows since net flux is zero
    if (isZero) return;

    // Circular Array of Radial White Arrows (Outward for Source, Inward for Sink)
    for (let a = 0; a < ringCount; a++) {
      const angle = (a / ringCount) * 2 * Math.PI;
      const rx = p.x + ringRadius * Math.cos(angle);
      const ry = p.y + ringRadius * Math.sin(angle);
      const radialDir = new THREE.Vector3(Math.cos(angle), Math.sin(angle), 0);

      if (isSource) {
        // Outward radiating white arrow
        const arr = new THREE.ArrowHelper(
          radialDir,
          new THREE.Vector3(rx, ry, 0.03),
          0.32,
          0xffffff,
          0.13,
          0.08
        );
        arr.line.material.linewidth = 3;
        ringsGroup.add(arr);
      } else {
        // Inward converging white arrow
        const inwardDir = radialDir.clone().negate();
        const startPos = new THREE.Vector3(
          p.x + (ringRadius + 0.32) * Math.cos(angle),
          p.y + (ringRadius + 0.32) * Math.sin(angle),
          0.03
        );
        const arr = new THREE.ArrowHelper(
          inwardDir,
          startPos,
          0.32,
          0xffffff,
          0.13,
          0.08
        );
        arr.line.material.linewidth = 3;
        ringsGroup.add(arr);
      }
    }
  });

  // 3. Animated Flowing Particle Streamlines
  initParticles();
}

function initParticles() {
  particlePositions = new Float32Array(NUM_PARTICLES * 3);
  particleData = [];

  const sources = points.filter(pt => pt.q > 0.05);

  for (let i = 0; i < NUM_PARTICLES; i++) {
    let x, y;
    if (sources.length > 0) {
      const src = sources[Math.floor(Math.random() * sources.length)];
      const randAngle = Math.random() * 2 * Math.PI;
      const randR = 0.2 + Math.random() * 1.5;
      x = src.x + randR * Math.cos(randAngle);
      y = src.y + randR * Math.sin(randAngle);
    } else {
      // Solenoidal flow: uniform distribution across plane
      x = -3.8 + Math.random() * 7.6;
      y = -2.6 + Math.random() * 5.2;
    }

    particlePositions[i * 3] = x;
    particlePositions[i * 3 + 1] = y;
    particlePositions[i * 3 + 2] = 0.04;

    particleData.push({
      x, y,
      speed: 0.9 + Math.random() * 0.8,
      life: Math.random() * 80,
      maxLife: 60 + Math.random() * 80
    });
  }

  const pGeo = new THREE.BufferGeometry();
  pGeo.setAttribute('position', new THREE.BufferAttribute(particlePositions, 3));
  const pMat = new THREE.PointsMaterial({
    color: 0x67e8f9,
    size: 0.09,
    transparent: true,
    opacity: 0.85,
    blending: THREE.AdditiveBlending
  });
  particlesMesh = new THREE.Points(pGeo, pMat);
  divergenceGroup.add(particlesMesh);
}

/**
 * Uniform Topic Module Contract: update()
 */
export function update(time, coordSystem, params) {
  // Check if points data changed
  if (params.divPoints) {
    let changed = false;
    for (let i = 0; i < 4; i++) {
      if (Math.abs(params.divPoints[i].x - points[i].x) > 0.01 ||
          Math.abs(params.divPoints[i].y - points[i].y) > 0.01 ||
          Math.abs(params.divPoints[i].q - points[i].q) > 0.01) {
        changed = true;
        break;
      }
    }
    if (changed) {
      points = JSON.parse(JSON.stringify(params.divPoints));
      buildScene(params);
    }
  }

  if (vectorsGroup) vectorsGroup.visible = params.showVectors !== false;
  if (ringsGroup) ringsGroup.visible = params.showSurfaces !== false;

  // Animate fluid particles along field lines
  if (particlesMesh && particlePositions && particleData.length > 0) {
    const dt = 0.016;

    for (let i = 0; i < NUM_PARTICLES; i++) {
      const p = particleData[i];
      p.life += dt * 30;

      const { Fx, Fy, mag } = evalField(p.x, p.y);

      if (p.life > p.maxLife || mag < 0.02 || Math.abs(p.x) > 4.2 || Math.abs(p.y) > 3.0) {
        // Respawn near an active positive source if available; otherwise uniform / left stream
        const sources = points.filter(pt => pt.q > 0.05);
        if (sources.length > 0) {
          const spawnCenter = sources[Math.floor(Math.random() * sources.length)];
          const ang = Math.random() * 2 * Math.PI;
          const rad = 0.15 + Math.random() * 0.45;
          p.x = spawnCenter.x + rad * Math.cos(ang);
          p.y = spawnCenter.y + rad * Math.sin(ang);
        } else {
          // Solenoidal flow: uniform distribution or left intake
          p.x = -3.8 + Math.random() * 0.4;
          p.y = -2.5 + Math.random() * 5.0;
        }
        p.life = 0;
      } else {
        const step = p.speed * dt * 1.5;
        p.x += (Fx / (mag + 0.5)) * step;
        p.y += (Fy / (mag + 0.5)) * step;
      }

      particlePositions[i * 3] = p.x;
      particlePositions[i * 3 + 1] = p.y;
    }
    particlesMesh.geometry.attributes.position.needsUpdate = true;
  }
}

